"""Prompt template for the Reviewer Agent's Part B (qualitative critique).

Part A (deterministic rule-checks) is implemented purely in code — see
agents/reviewer.py `run_rule_checks()`. This prompt is used ONLY for Part B,
and should ideally be sent to a DIFFERENT model/provider than the one that
generated the proposal (see services/llm.py `judge()`), to reduce
same-family leniency bias.
"""
import json

REVIEWER_SCHEMA_HINT = """{
  "strengths": ["..."],
  "weaknesses": ["..."],
  "missing_components": ["..."],
  "novelty_score": 0.0,
  "quality_score": 0.0
}"""


def build_reviewer_critique_prompt(topic: str, full_proposal: dict, rule_check_results: dict) -> str:
    proposal_block = json.dumps(full_proposal, indent=2)
    rules_block = json.dumps(rule_check_results, indent=2)
    return f"""You are the Reviewer Agent's qualitative critique component, reviewing a
research proposal generated by a DIFFERENT AI system. Be candid and critical
— do not default to praise.

Research topic: "{topic}"

Full proposal:
{proposal_block}

Deterministic rule-check results already computed in code (Part A):
{rules_block}

Your critique (Part B) must explicitly reference Part A's results where
relevant, e.g. "2 of 5 claimed gaps lack supporting paper references —
treat with caution."

Provide:
- 3-5 strengths (specific, not generic praise).
- 3-5 weaknesses (specific and actionable).
- 1-4 missing_components (things a solid proposal on this topic should have
  but this one lacks).
- novelty_score (0.0-1.0): how novel is the proposed research direction
  relative to the reviewed literature.
- quality_score (0.0-1.0): overall rigor and coherence of the proposal.

Respond with ONLY valid JSON matching this exact shape, no prose:
{REVIEWER_SCHEMA_HINT}
"""
